"""Failure signatures: what kind of failure a client saw, and which component produced it.

Every failed availability probe and every failed load-generator request is classified as one of

    rejected_by_proxy   a 4xx generated by nginx (429 limit_req, 403 deny, 444 …)
    upstream_down       502/503/504 from nginx, or the connection was refused
    app_error           a 5xx generated by Gitea
    tls_error           certificate or handshake failure
    timeout             connect or read timeout
    network_error       reset, unreachable, aborted without an answer

plus `app_rejected` for a 4xx that Gitea itself sent (an application answer, e.g. 404/401) —
not an availability failure of the front end, but recorded so nothing is silently dropped.

Which component answered is decided from the response itself: nginx's default error page
("<center>nginx</center>") versus Gitea's markers (its cookies `i_like_gitea`/`_csrf`, its JSON
error bodies with a `message`, the `X-Gitea-*` headers). nginx never forwards upstream
cookies onto its own error pages, so the two cannot be confused. Where only a status code was
stored (runs before this classification existed), `component` is "unknown" and the status
alone decides: 429/444 and 403 are taken as proxy rejections, because Gitea sends neither on
the probe's endpoints.
"""
from __future__ import annotations

import re
from typing import Any, Mapping

SIGNATURES = ("rejected_by_proxy", "upstream_down", "app_error", "tls_error", "timeout", "network_error")
EXTRA = ("app_rejected",)

# When one probe saw several failures (health endpoint and API), the one closest to the service
# itself wins: a front end that rejects a client says nothing about whether the service is up.
PRIORITY = ("tls_error", "upstream_down", "app_error", "timeout", "network_error", "rejected_by_proxy",
            "app_rejected")

_NGINX_PAGE = re.compile(rb"<center>nginx(?:/[\d.]+)?</center>", re.I)
_PROXY_STATUSES = {403, 429, 444}


def component_of(status: int | None, headers: Mapping[str, str] | None = None, body: bytes | str | None = None) -> str:
    """"nginx", "gitea" or "unknown"."""
    headers = {k.lower(): v for k, v in (headers or {}).items()}
    raw = body.encode("utf-8", "replace") if isinstance(body, str) else (body or b"")
    head = raw[:4096]
    if _NGINX_PAGE.search(head):
        return "nginx"
    cookies = headers.get("set-cookie", "")
    if "i_like_gitea" in cookies or "_csrf=" in cookies or any(k.startswith("x-gitea") for k in headers):
        return "gitea"
    ctype = headers.get("content-type", "")
    if "json" in ctype and (b'"message"' in head or b'"errors"' in head):
        return "gitea"
    if status == 444 or (status is not None and status >= 400 and headers and not head.strip()):
        return "nginx"        # nginx closes or answers with an empty body; Gitea always explains
    return "unknown"


def classify_response(status: int | None, headers: Mapping[str, str] | None = None,
                      body: bytes | str | None = None) -> tuple[str | None, str]:
    """(signature, component) for an HTTP answer; signature is None for a success (< 400)."""
    if status is None or status < 400:
        return None, component_of(status, headers, body) if headers else "unknown"
    comp = component_of(status, headers, body)
    return signature_of_status(status, comp), comp


def signature_of_status(status: int, component: str = "unknown") -> str:
    if status >= 500:
        if component == "gitea":
            return "app_error"
        if status in (502, 503, 504) or component == "nginx":
            return "upstream_down"
        return "app_error"
    if component == "nginx":
        return "rejected_by_proxy"
    if component == "gitea":
        return "app_rejected"
    return "rejected_by_proxy" if status in _PROXY_STATUSES else "app_rejected"


def classify_error(text: str) -> str:
    """Signature of a transport failure, from an exception's type name and message."""
    t = text.lower()
    if any(k in t for k in ("certificate", "ssl", "tls", "handshake")):
        return "tls_error"
    if "timeout" in t or "timed out" in t:
        return "timeout"
    if "refused" in t:
        return "upstream_down"
    return "network_error"


def classify_exception(exc: BaseException) -> tuple[str, str]:
    """(signature, component) for a requests/urllib3/socket exception."""
    import requests                                    # optional dependency for the scorer
    if isinstance(exc, requests.exceptions.SSLError):
        return "tls_error", "nginx"
    if isinstance(exc, (requests.exceptions.ConnectTimeout, requests.exceptions.ReadTimeout,
                        requests.exceptions.Timeout)):
        return "timeout", "unknown"
    return classify_error(f"{type(exc).__name__}: {exc}"), "unknown"


_GIT_STATUS = re.compile(r"returned error: (\d{3})")


def classify_git_error(stderr: str) -> str:
    """Signature of a failed `git` over HTTPS, from its stderr."""
    m = _GIT_STATUS.search(stderr)
    if m:
        return signature_of_status(int(m.group(1)))
    return classify_error(stderr)


def part_signature(part: Mapping[str, Any] | None) -> str | None:
    """Signature of one stored probe part ({status, error, signature?, component?})."""
    if not part:
        return None
    if part.get("signature"):
        return part["signature"]
    status, error = part.get("status"), part.get("error")
    if error:
        return classify_error(str(error))
    if status is None or status < 400:
        return None
    return signature_of_status(int(status), part.get("component") or "unknown")


def probe_signature(payload: Mapping[str, Any]) -> str | None:
    """The signature of one http_availability probe (None if it passed)."""
    if payload.get("ok"):
        return None
    found = [s for s in (part_signature(payload.get(p)) for p in ("healthz", "api")) if s]
    if not found:
        return "network_error"
    return min(found, key=lambda s: PRIORITY.index(s) if s in PRIORITY else len(PRIORITY))


def dominant(signatures: list[str]) -> str | None:
    """Most frequent signature; ties go to the one closest to the service (PRIORITY order)."""
    if not signatures:
        return None
    counts: dict[str, int] = {}
    for s in signatures:
        counts[s] = counts.get(s, 0) + 1
    return min(counts, key=lambda s: (-counts[s], PRIORITY.index(s) if s in PRIORITY else len(PRIORITY)))


def rejected_by_access_control(status: int | None, headers: Mapping[str, str] | None = None,
                               body: bytes | str | None = None) -> str | None:
    """If this answer is target-side access control (a 4xx nginx generated), the reason; else None.
    Used to mark checks inconclusive instead of failed."""
    if status is None or not 400 <= status < 500:
        return None
    comp = component_of(status, headers, body)
    if comp == "nginx" or (comp == "unknown" and status in _PROXY_STATUSES):
        return f"rejected by target-side access control: HTTP {status} generated by nginx"
    return None
